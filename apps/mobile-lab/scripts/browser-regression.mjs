import assert from 'node:assert/strict'
import { createServer } from 'node:http'
import { readFile, mkdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { app, require } from './build-support.mjs'

export async function browserRegression({ outdir, catalog }) {
  const { chromium } = require('@playwright/test')
  const errors = [], requests = []
  const server = createServer(async (req, res) => {
    try {
      const url = new URL(req.url, 'http://localhost')
      if (url.pathname === '/untrusted-frame') { res.setHeader('content-type', 'text/html'); res.end('<!doctype html><title>Untrusted frame</title>'); return }
      if (!url.pathname.startsWith('/assets/lab/')) { res.writeHead(404); res.end(); return }
      const relative = decodeURIComponent(url.pathname.slice('/assets/lab/'.length))
      const file = path.resolve(outdir, relative || 'index.html')
      if (!file.startsWith(outdir + path.sep)) throw new Error('path')
      const content = await readFile(file)
      const type = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json', '.png': 'image/png', '.woff2': 'font/woff2', '.woff': 'font/woff', '.ttf': 'font/ttf' }[path.extname(file)]
      res.setHeader('content-type', type || 'application/octet-stream'); res.end(content)
    } catch { res.writeHead(404); res.end() }
  })
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
  const origin = `http://127.0.0.1:${server.address().port}`, base = `${origin}/assets/lab/`
  let browser
  try {
    const options = { headless: true }
    if (process.env.PHYSICSOS_TEST_BROWSER) options.executablePath = process.env.PHYSICSOS_TEST_BROWSER
    // Browser installation is never performed here. Existing Chrome/Edge is a valid local runner.
    try { browser = await chromium.launch(options) }
    catch (first) {
      if (options.executablePath) throw first
      try { browser = await chromium.launch({ headless: true, channel: 'msedge' }) }
      catch { throw new Error(`No already-installed Playwright Chromium or Edge browser. Set PHYSICSOS_TEST_BROWSER to an existing executable. No browser was installed. ${first.message}`) }
    }
    const context = await browser.newContext({ viewport: { width: 412, height: 915 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 })
    await context.route('**/*', route => {
      const url = new URL(route.request().url())
      if (url.origin !== origin) { requests.push({ url: url.href, blocked: true }); return route.abort() }
      return route.continue()
    })
    const page = await context.newPage()
    page.on('pageerror', error => errors.push(error.stack || error.message))
    page.on('response', response => { if (response.status() >= 400) requests.push({ url: response.url(), status: response.status() }) })
    await page.goto(`${base}index.html`)
    await page.getByTestId('lab-app').waitFor()
    assert.equal(await page.locator('[data-template]').count(), catalog.experiments.length)
    await page.locator('[data-template="projectile-oblique"]').click()
    await page.getByTestId('physics-scene').waitFor()
    await page.getByTestId('step').click()
    await page.waitForFunction(() => window.__physicsLab.getSnapshot().frame.clock.time > 0)
    await page.getByTestId('play-pause').click()
    await page.waitForFunction(() => window.__physicsLab.getSnapshot().frame.clock.running)
    await page.getByTestId('play-pause').click()
    await page.waitForFunction(() => !window.__physicsLab.getSnapshot().frame.clock.running)
    await page.getByRole('button', { name: '参数与场景', exact: true }).click()
    const input = page.locator('.parameter input[type="number"]').first()
    const oldValue = Number(await input.inputValue())
    await input.fill(''); await input.blur()
    await page.locator('.parameter-error').first().waitFor()
    assert.equal(await page.evaluate(() => window.__physicsLab.getSnapshot().summary.history.canUndo), false, 'invalid input must not change the scene')
    await input.fill(String(oldValue + 1)); await input.blur()
    await page.waitForFunction(() => window.__physicsLab.getSnapshot().summary.history.canUndo)
    await page.locator('.playback-more > summary').click()
    await page.getByRole('button', { name: '撤销', exact: true }).click()
    await page.waitForFunction(() => window.__physicsLab.getSnapshot().summary.history.canRedo)
    await page.getByRole('button', { name: '重做', exact: true }).click()
    await page.locator('.playback-more > summary').click()
    await page.getByRole('button', { name: '读数与曲线', exact: true }).click()
    await page.locator('.curve-plot').first().waitFor()
    await page.locator('.curve-plot').first().focus(); await page.keyboard.press('ArrowRight')
    assert.ok((await page.locator('.curve-reading').first().innerText()).length > 0)
    await page.locator('.curve summary').first().click()
    await page.locator('.curve table tbody tr').first().waitFor()
    await page.getByRole('button', { name: '验证与自测', exact: true }).click()
    assert.ok(await page.locator('.verification li').count() > 0)
    await page.getByRole('button', { name: '观察与报告', exact: true }).click()
    await page.getByRole('button', { name: '记录此刻观察', exact: true }).click()
    await page.waitForFunction(() => window.__physicsLab.getSnapshot().summary.notebook.length > 0)
    await page.locator('.playback-more > summary').click()
    await page.getByTestId('save-scene').click()
    await page.locator('.playback-more > summary').click()
    await page.getByRole('status').filter({ hasText: '完整场景' }).waitFor()
    const checkpoint = await page.evaluate(() => window.__physicsLab.checkpoint())
    await page.reload()
    await page.getByRole('button', { name: '读取本地存档', exact: true }).click()
    await page.getByRole('button', { name: '恢复', exact: true }).click()
    await page.getByTestId('physics-scene').waitFor()
    const restored = await page.evaluate(() => window.__physicsLab.checkpoint())
    assert.deepEqual(restored, checkpoint)
    await page.getByTestId('open-catalog').click()
    await page.getByRole('button', { name: '自由搭建电路', exact: true }).click()
    // Unsaved-change confirmation uses native browser dialog, never suppresses persistence errors.
    page.on('dialog', dialog => dialog.accept())
    await page.getByRole('button', { name: '器材与搭建', exact: true }).click()
    await page.locator('[data-part="resistor-20"]').click()
    await page.waitForFunction(() => window.__physicsLab.getSnapshot().summary.draft.components.some(component => component.id === 'r1'))
    await page.getByRole('button', { name: '旋转 90°', exact: true }).click()
    await page.waitForFunction(() => window.__physicsLab.getSnapshot().summary.draft.components.find(component => component.id === 'r1').placement.rotation === 90)
    // Close the inspector before touching the canvas, just as on the phone; do not
    // force a tap through an overlaid panel and mistake that for a wiring failure.
    await page.getByRole('button', { name: '收起面板', exact: true }).click()
    const terminals = page.locator('[data-terminal-hit]')
    assert.ok(await terminals.count() > 1)
    await terminals.nth(0).tap()
    await page.waitForFunction(() => window.__physicsLab.getSnapshot().summary.pendingWire !== undefined)
    await page.getByRole('button', { name: '器材与搭建', exact: true }).click()
    await page.getByRole('button', { name: '取消接线', exact: true }).click()
    await page.getByRole('button', { name: '完成搭建，保留电路', exact: true }).click()
    await page.locator('.playback-more > summary').click()
    await page.getByTestId('save-scene').click()
    await page.locator('.playback-more > summary').click()
    // Dedicated lens inquiry reuses the actual Web optical bench, not a simulated UI fixture.
    await page.evaluate(() => window.__physicsLab.load({ templateId: 'convex-lens' }))
    await page.getByTestId('lens-stage').waitFor()
    const lensParameter = id => page.evaluate(id => window.__physicsLab.frames.getSnapshot().inspector.flatMap(section => section.parameters ?? []).find(parameter => parameter.id === id).value, id)
    const objectHandle = page.getByRole('slider', { name: '拖动物体', exact: true })
    const objectStart = await lensParameter('object-distance')
    await objectHandle.focus(); await page.keyboard.press('ArrowRight')
    await page.waitForFunction(value => window.__physicsLab.frames.getSnapshot().inspector.flatMap(section => section.parameters ?? []).find(parameter => parameter.id === 'object-distance').value === value, objectStart + 0.5)
    const beforeDrag = await lensParameter('object-distance')
    const handleBox = await objectHandle.boundingBox()
    await page.mouse.move(handleBox.x + handleBox.width / 2, handleBox.y + 35)
    await page.mouse.down(); await page.mouse.move(handleBox.x + handleBox.width / 2 - 20, handleBox.y + 35, { steps: 6 }); await page.mouse.up()
    await page.waitForFunction(value => window.__physicsLab.frames.getSnapshot().inspector.flatMap(section => section.parameters ?? []).find(parameter => parameter.id === 'object-distance').value !== value, beforeDrag)
    await page.getByRole('button', { name: '参数与场景', exact: true }).click()
    await page.getByTestId('lens-preset-magnifier').click()
    await page.waitForFunction(() => window.__physicsLab.frames.getSnapshot().view.opticalImages?.[0]?.nature === 'virtual')
    await page.getByTestId('lens-record').click()
    await page.waitForFunction(() => window.__physicsLab.getSnapshot().summary.notebook.length === 1)
    await page.getByTestId('lens-preset-camera').click()
    await page.waitForFunction(() => window.__physicsLab.frames.getSnapshot().view.opticalImages?.[0]?.nature === 'real')
    await page.getByTestId('lens-record').click()
    await page.waitForFunction(() => window.__physicsLab.getSnapshot().summary.notebook.length === 2)
    await page.getByRole('button', { name: '恢复初始装置', exact: true }).click()
    await page.getByRole('button', { name: '确认恢复装置', exact: true }).click()
    await page.waitForFunction(() => !document.querySelector('[role="alertdialog"]'))
    assert.equal(await page.evaluate(() => window.__physicsLab.getSnapshot().summary.notebook.length), 2, 'reset must not discard observations')
    await page.getByRole('button', { name: '读数与曲线', exact: true }).click()
    assert.equal(await page.getByTestId('observation-table').locator('tbody tr').count(), 2)
    await page.getByRole('button', { name: '收起面板', exact: true }).click()
    // All real templates: real module Worker load, renderer, readout, checkpoint, one step.
    const observed = []
    for (const template of catalog.experiments) {
      await page.evaluate(async id => { const client = window.__physicsLab; await client.load({ templateId: id }); await client.action('step', 1 / 60) }, template.id)
      await page.waitForFunction(id => window.__physicsLab.getSnapshot().summary?.templateId === id && !!document.querySelector('[data-testid="physics-scene"] svg'), template.id)
      const result = await page.evaluate(async () => {
        const client = window.__physicsLab, frame = client.frames.getSnapshot(), saved = await client.checkpoint()
        return { id: client.getSnapshot().summary.templateId, status: frame.status, domain: frame.domain, time: frame.clock.time,
          history: !!saved.history, size: document.querySelector('[data-testid="physics-scene"]').getBoundingClientRect().width,
          imageUrls: [...document.querySelectorAll('svg image')].map(image => image.getAttribute('href')) }
      })
      assert.equal(result.id, template.id); assert.equal(result.domain, template.domain); assert.ok(result.history); assert.ok(result.size > 200)
      assert.ok(result.imageUrls.every(url => !url || url.startsWith('./assets/') || url.startsWith('data:')), `nonlocal renderer asset for ${template.id}`)
      observed.push(result)
    }
    assert.equal(observed.length, catalog.experiments.length)
    // Native bridge isolated page with actual browser Worker and recorded coarse bridge messages.
    const nativePage = await context.newPage()
    nativePage.on('pageerror', error => errors.push(error.message))
    await nativePage.addInitScript(() => { window.__nativeMessages = []; window.PhysicsNative = { postMessage: raw => window.__nativeMessages.push({ at: performance.now(), ...JSON.parse(raw) }) } })
    await nativePage.goto(`${base}index.html`)
    await nativePage.waitForFunction(() => window.__nativeMessages.some(message => message.type === 'ready'))
    const gen = crypto.randomUUID(), nextGen = crypto.randomUUID()
    const command = (target, type, payload, id = crypto.randomUUID()) => target.evaluate(({ type, payload, id }) => window.postMessage(JSON.stringify({ version: 1, id, type, payload }), location.origin), { type, payload, id })
    await nativePage.evaluate(gen => window.dispatchEvent(new MessageEvent('message', { origin: '', source: null,
      data: JSON.stringify({ version: 1, id: 'android-native-load', type: 'load', payload: { generation: gen, templateId: 'projectile-oblique' } }) })), gen)
    await nativePage.getByTestId('physics-scene').waitFor()
    assert.equal(await nativePage.locator('.lab-header').count(), 0, 'embedded lab must not duplicate the native title bar')
    assert.equal(await nativePage.getByTestId('save-scene').count(), 0, 'embedded lab uses the real native save, not a duplicate button')
    assert.equal(await nativePage.locator('.panel-content').count(), 0, 'inspector starts collapsed so the canvas owns the first screen')
    const canvasBox = await nativePage.getByTestId('physics-scene').boundingBox()
    assert.ok(canvasBox.y < 40 && canvasBox.height > 500 && canvasBox.width > 370, 'embedded canvas must occupy the main viewport without a blank side gutter')
    await nativePage.getByTestId('play-pause').click()
    await nativePage.waitForFunction(() => window.__nativeMessages.filter(message => message.type === 'state').length >= 5)
    const states = await nativePage.evaluate(() => window.__nativeMessages.filter(message => message.type === 'state'))
    for (let i = 1; i < states.length; i++) assert.ok(states[i].at - states[i - 1].at >= 245, 'native summaries must be <=4Hz')
    assert.ok(states.every(message => !message.payload.scene && !message.payload.charts && !message.payload.view))
    await command(nativePage, 'lifecycle', { generation: gen, active: false }, 'suspend')
    await nativePage.waitForFunction(() => window.__nativeMessages.some(message => message.type === 'checkpoint' && message.id === 'suspend'))
    const suspended = await nativePage.evaluate(() => window.__nativeMessages.find(message => message.id === 'suspend').payload.checkpoint)
    assert.equal(suspended.playback.running, false)
    const time = suspended.playback.time
    await nativePage.waitForTimeout(350)
    assert.equal(await nativePage.evaluate(() => window.__physicsLab.frames.getSnapshot().clock.time), time)
    await command(nativePage, 'load', { generation: nextGen, checkpoint: suspended })
    await nativePage.waitForFunction(gen => window.__physicsLab.getSnapshot().generation === gen && !window.__physicsLab.getSnapshot().loading, nextGen)
    await command(nativePage, 'theme', { generation: gen, dark: true })
    await command(nativePage, 'load', { generation: gen, templateId: 'series-circuit' })
    await nativePage.waitForTimeout(100)
    assert.equal(await nativePage.evaluate(() => window.__physicsLab.getSnapshot().generation), nextGen)
    assert.equal(await nativePage.evaluate(() => window.__physicsLab.getSnapshot().summary.templateId), 'projectile-oblique')
    await command(nativePage, 'export', { generation: nextGen, format: 'json' }, 'export-json')
    await nativePage.waitForFunction(() => window.__nativeMessages.some(message => message.id === 'export-json' && message.type === 'export'))
    await command(nativePage, 'checkpoint', { generation: nextGen }, 'saved')
    await nativePage.waitForFunction(() => window.__nativeMessages.some(message => message.id === 'saved' && message.type === 'checkpoint'))
    // Wrong origin and iframe source cannot invoke a privileged native operation.
    const before = await nativePage.evaluate(() => window.__nativeMessages.length)
    await nativePage.evaluate(gen => window.dispatchEvent(new MessageEvent('message', { origin: 'https://evil.invalid', source: window, data: JSON.stringify({ version: 1, id: 'evil', type: 'export', payload: { generation: gen, format: 'json' } }) })), nextGen)
    await nativePage.evaluate(async gen => {
      const iframe = document.createElement('iframe'); iframe.src = '/untrusted-frame'; document.body.append(iframe)
      await new Promise(resolve => { iframe.onload = resolve })
      window.dispatchEvent(new MessageEvent('message', { origin: location.origin, source: iframe.contentWindow, data: JSON.stringify({ version: 1, id: 'child', type: 'export', payload: { generation: gen, format: 'json' } }) }))
      iframe.remove()
    }, nextGen)
    await nativePage.waitForTimeout(100)
    assert.ok(!(await nativePage.evaluate(() => window.__nativeMessages)).some(message => ['evil', 'child'].includes(message.id)))
    // Separate math document accepts text/Markdown only; links/images cannot reach a remote origin.
    const documentPage = await context.newPage()
    documentPage.on('pageerror', error => errors.push(error.message))
    await documentPage.addInitScript(() => { window.__nativeMessages = []; window.PhysicsNative = { postMessage: raw => window.__nativeMessages.push(JSON.parse(raw)) } })
    await documentPage.goto(`${base}document.html`)
    const docGen = crypto.randomUUID()
    const blocks = [{ id: 'a', markdown: '# 公式\n\n$E=mc^2$\n\n<script>window.attack=1</script>\n\n![blocked](https://evil.invalid/x.png)' }, { id: 'b', text: '<b>这必须是纯文本</b>' }]
    await command(documentPage, 'document', { generation: docGen, title: '恢复与安全文档', blocks })
    await documentPage.locator('.katex').first().waitFor()
    assert.equal(await documentPage.locator('#document script, #document iframe, #document img').count(), 0)
    assert.equal(await documentPage.evaluate(() => window.attack), undefined)
    assert.ok((await documentPage.locator('[data-block-id="b"]').innerText()).includes('<b>'))
    await documentPage.evaluate(() => { window.__firstBlock = document.querySelector('[data-block-id="a"]') })
    await command(documentPage, 'document', { generation: docGen, title: '恢复与安全文档', blocks: [blocks[0], { id: 'b', text: '追加的新内容' }] })
    await documentPage.getByText('追加的新内容', { exact: true }).waitFor()
    assert.ok(await documentPage.evaluate(() => window.__firstBlock === document.querySelector('[data-block-id="a"]')), 'completed math blocks must retain DOM')
    await command(documentPage, 'theme', { generation: docGen, dark: true })
    assert.equal(await documentPage.evaluate(() => document.documentElement.dataset.theme), 'dark')
    // Render inspection artifacts and measured diagnostics are local only, never invented device scores.
    const artifacts = path.join(app, '.cache/browser-artifacts'); await mkdir(artifacts, { recursive: true })
    assert.equal(await page.locator('.error-banner').count(), 0, 'template changes must not leave a stale-operation error')
    await page.screenshot({ path: path.join(artifacts, 'mobile-lab.png'), fullPage: true })
    await nativePage.screenshot({ path: path.join(artifacts, 'native-experiment.png'), fullPage: true })
    await nativePage.getByRole('button', { name: '参数与场景', exact: true }).click()
    await nativePage.locator('.parameter').first().waitFor()
    await nativePage.screenshot({ path: path.join(artifacts, 'native-parameters.png'), fullPage: true })
    await nativePage.getByRole('button', { name: '收起面板', exact: true }).click()
    const lensGeneration = crypto.randomUUID()
    await command(nativePage, 'load', { generation: lensGeneration, templateId: 'convex-lens' })
    await nativePage.getByTestId('lens-stage').waitFor()
    await nativePage.screenshot({ path: path.join(artifacts, 'lens-inquiry.png'), fullPage: true })
    await nativePage.getByRole('button', { name: '参数与场景', exact: true }).click()
    await nativePage.getByTestId('lens-preset-focus').click()
    await nativePage.waitForFunction(() => window.__physicsLab.frames.getSnapshot().view.opticalImages?.length === 0)
    await nativePage.screenshot({ path: path.join(artifacts, 'lens-focus-controls.png'), fullPage: true })
    const nativeLensBox = await nativePage.getByTestId('physics-scene').boundingBox()
    const nativeInspector = await nativePage.locator('.inspector').boundingBox()
    assert.ok(nativeLensBox.y + nativeLensBox.height <= nativeInspector.y + 1, 'lens controls must not cover the active optical bench')
    await nativePage.getByTestId('lens-preset-camera').click()
    await nativePage.getByTestId('lens-record').click()
    await nativePage.waitForFunction(() => window.__physicsLab.getSnapshot().summary.notebook.length === 1)
    await command(nativePage, 'export', { generation: lensGeneration, format: 'observations' }, 'export-observations')
    await nativePage.waitForFunction(() => window.__nativeMessages.some(message => message.id === 'export-observations' && message.type === 'export'))
    const observationFile = await nativePage.evaluate(() => window.__nativeMessages.find(message => message.id === 'export-observations').payload)
    assert.equal(observationFile.mime, 'text/csv'); assert.ok(observationFile.name.endsWith('.csv')); assert.ok(observationFile.content.includes('场景修订'))
    await nativePage.getByRole('button', { name: '读数与曲线', exact: true }).click()
    await nativePage.getByTestId('observation-table').waitFor()
    await nativePage.screenshot({ path: path.join(artifacts, 'lens-observation-table.png'), fullPage: true })
    await page.setViewportSize({ width: 320, height: 740 })
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), 'narrow phones must not overflow horizontally')
    await page.screenshot({ path: path.join(artifacts, 'small-phone.png'), fullPage: true })
    await page.setViewportSize({ width: 1180, height: 820 })
    await page.getByRole('button', { name: '深色界面', exact: true }).click()
    await page.screenshot({ path: path.join(artifacts, 'tablet-dark.png'), fullPage: true })
    await documentPage.screenshot({ path: path.join(artifacts, 'document-dark.png'), fullPage: true })
    await writeFile(path.join(artifacts, 'result.json'), JSON.stringify({ version: 1, environment: 'local desktop browser, mobile touch emulation; NOT Android performance acceptance', templates: observed, nativeStateIntervalsMs: states.slice(1).map((state, i) => state.at - states[i].at), clientMetrics: await page.evaluate(() => window.__physicsLab.metrics.snapshot()), errors, requests }, null, 2))
    assert.deepEqual(errors, [], 'uncaught browser exceptions')
    assert.deepEqual(requests, [], 'all executable/assets must resolve locally; no remote requests')
    console.log(`Browser regression passed: ${observed.length} real templates, touch editing, offline assets, native 4Hz/generation/source isolation, persistence recovery and math sanitization. Artifacts: ${artifacts}`)
  } finally { await browser?.close(); await new Promise(resolve => server.close(resolve)) }
}
