/**
 * 实验贡献 — the community contribution area under 探索.
 *
 * The docs portal at `/physicsos/developers/` owns the standard itself (package
 * format, protocol, visual rules, downloadable template). This surface is the
 * product-side front door to it: what a contributor delivers, what the platform
 * owns, and the honest state of the upload path.
 *
 * It deliberately does NOT render a fake upload form or a PR link. Server-side
 * submission, review and default-version switching are a platform capability
 * that is not built yet, so the page says so and points at the real part —
 * the template and the docs — instead of inventing a flow that cannot work.
 */

import clsx from 'clsx'
import type { ReactElement } from 'react'
import { IconChevronRightOutlineMedium } from '@deepseek-ai/dsh-client-ui-primitives'
import type { ProductSurfaceBaseProps } from './surface-props.ts'
import type { PhysicsosKey } from './locales.ts'
import { IconContribution } from './icons/physics-icons.tsx'
import { Mascot } from './Mascot.tsx'
import css from './ContributeWorkspace.module.css'

/** The portal page generated by `scripts/developers/generate.mjs`. */
const DOCS_HREF = '/physicsos/developers/index.html'

/** One numbered step of the contribution path. */
interface Step {
  readonly title: PhysicsosKey
  readonly body: PhysicsosKey
  /** Only the parts that work today are marked available. */
  readonly available: boolean
}

const STEPS: readonly Step[] = [
  { title: 'contribute.step1.title', body: 'contribute.step1.body', available: true },
  { title: 'contribute.step2.title', body: 'contribute.step2.body', available: true },
  { title: 'contribute.step3.title', body: 'contribute.step3.body', available: false },
  { title: 'contribute.step4.title', body: 'contribute.step4.body', available: false },
]

/** What the platform provides versus what the contributor owns. */
const DIVISION: ReadonlyArray<{ platform: PhysicsosKey; author: PhysicsosKey }> = [
  { platform: 'contribute.split.route', author: 'contribute.split.view' },
  { platform: 'contribute.split.engine', author: 'contribute.split.interaction' },
  { platform: 'contribute.split.records', author: 'contribute.split.assets' },
  { platform: 'contribute.split.review', author: 'contribute.split.cases' },
]

/**
 * Render the contribution area.
 * @param props - product copy; this surface reads no runtime or scene state.
 * @returns the contributor landing page.
 */
export function ContributeWorkspace({ t }: ProductSurfaceBaseProps): ReactElement {
  return (
    <div className={css.cover} data-physicsos-surface="contribute">
      <header className={css.header}>
        <Mascot pose="think" size={64} className={css.mascot} />
        <div className={css.headerCopy}>
          <span className={css.eyebrow}>{t('contribute.eyebrow')}</span>
          <h1 className={css.title}>{t('contribute.title')}</h1>
          <p className={css.subtitle}>{t('contribute.subtitle')}</p>
        </div>
        <a className={css.primaryAction} href={DOCS_HREF} target="_blank" rel="noopener noreferrer">
          {t('contribute.openDocs')}
        </a>
      </header>

      <div className={css.body}>
        <section className={css.card} aria-labelledby="contribute-path">
          <div className={css.cardHead}>
            <span className={css.cardIcon} aria-hidden="true"><IconContribution size={16} /></span>
            <h2 id="contribute-path" className={css.cardTitle}>{t('contribute.path.title')}</h2>
          </div>
          <ol className={css.steps}>
            {STEPS.map((step, index) => (
              <li key={step.title} className={clsx(css.step, !step.available && css.stepLocked)}>
                <span className={clsx(css.stepNumber, step.available && css.stepNumberReady)}>
                  {String(index + 1).padStart(2, '0')}
                </span>
                <div className={css.stepCopy}>
                  <strong className={css.stepTitle}>{t(step.title)}</strong>
                  <span className={css.stepBody}>{t(step.body)}</span>
                </div>
                <span className={clsx(css.stepState, step.available ? css.stateReady : css.statePending)}>
                  {t(step.available ? 'contribute.state.ready' : 'contribute.state.pending')}
                </span>
              </li>
            ))}
          </ol>
        </section>

        <section className={css.card} aria-labelledby="contribute-split">
          <div className={css.cardHead}>
            <span className={css.cardIcon} aria-hidden="true"><IconContribution size={16} /></span>
            <h2 id="contribute-split" className={css.cardTitle}>{t('contribute.split.title')}</h2>
          </div>
          <p className={css.cardBody}>{t('contribute.split.body')}</p>
          <div className={css.splitHead} aria-hidden="true">
            <span>{t('contribute.split.platform')}</span>
            <span>{t('contribute.split.author')}</span>
          </div>
          <ul className={css.split}>
            {DIVISION.map(pair => (
              <li key={pair.platform} className={css.splitRow}>
                <span>{t(pair.platform)}</span>
                <IconChevronRightOutlineMedium size={13} />
                <span>{t(pair.author)}</span>
              </li>
            ))}
          </ul>
        </section>
      </div>

      <aside className={css.notice}>
        <strong>{t('contribute.notice.title')}</strong>
        <p>{t('contribute.notice.body')}</p>
      </aside>
    </div>
  )
}
