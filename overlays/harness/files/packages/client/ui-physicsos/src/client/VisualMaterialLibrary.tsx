type Copy = { readonly [K in keyof typeof copy.zh]: string }
interface Filters { query: string; theme: string; purpose: string; kind: '' | VisualMaterialKind; tags: string; style: string; width: string; height: string; lifecycle: VisualMaterialLifecycle | 'all' }
const emptyFilters = (): Filters => ({ query: '', theme: '', purpose: '', kind: '', tags: '', style: '', width: '', height: '', lifecycle: 'all' })
const tagsOf = (value: string): string[] => [...new Set(value.split(/[,，]/).map(tag => tag.trim()).filter(Boolean))]
const dimension = (value: string): number | undefined => {
  if (!value.trim()) return undefined
  const parsed = Number(value)
  if (!Number.isSafeInteger(parsed) || parsed < 1 || parsed > 4096) throw new Error('invalid')
  return parsed
}
function searchInput(filters: Filters): VisualMaterialSearch {
  const tags = tagsOf(filters.tags), minWidth = dimension(filters.width), minHeight = dimension(filters.height)
  if (tags.length > 12 || tags.some(tag => tag.length > 48)) throw new Error('invalid')
  return { ...(filters.query.trim() ? { query: filters.query.trim() } : {}),
    ...(filters.theme.trim() ? { theme: filters.theme.trim() } : {}), ...(filters.purpose.trim() ? { purpose: filters.purpose.trim() } : {}),
    ...(filters.kind ? { kind: filters.kind } : {}), ...(tags.length ? { tags } : {}),
    ...(filters.style.trim() ? { style: filters.style.trim() } : {}),
    ...(minWidth === undefined ? {} : { minWidth }), ...(minHeight === undefined ? {} : { minHeight }), limit: 12 }
}
const errorText = (cause: unknown, c: Copy): string => cause instanceof VisualMaterialApiError
  ? cause.status === 401 ? c.auth : cause.status === 403 ? c.forbidden : cause.status === 409 ? c.conflict : cause.status === 404 ? c.missing : c.error : c.error
const normalize = (value: string): string => value.normalize('NFKC').toLowerCase().trim()
function matches(item: VisualMaterialDescriptor, filters: Filters): boolean {
  const query = normalize(filters.query), tags = tagsOf(filters.tags).map(normalize)
  const text = normalize([item.theme, item.purpose, item.style ?? '', ...item.tags].join(' '))
  return (!query || text.includes(query)) && (!filters.theme.trim() || normalize(item.theme) === normalize(filters.theme))
    && (!filters.purpose.trim() || normalize(item.purpose) === normalize(filters.purpose))
    && (!filters.kind || item.kind === filters.kind) && (!filters.style.trim() || normalize(item.style ?? '') === normalize(filters.style))
    && tags.every(tag => item.tags.some(value => normalize(value) === tag))
    && (!filters.width || item.width >= Number(filters.width)) && (!filters.height || item.height >= Number(filters.height))
}

function MaterialPreview({ item, api, c }: { item: VisualMaterialDescriptor; api: VisualMaterialApi; c: Copy }) {
  const [preview, setPreview] = useState<{ url: string; identity: string }>()
  const [failed, setFailed] = useState<string>()
  const [retry, setRetry] = useState(0)
  const identity = `${item.id}:${item.sha256}:${item.revision}`
  const activeIdentity = useRef(identity); activeIdentity.current = identity
  const activeApi = useRef(api); activeApi.current = api
  useEffect(() => {
    const controller = new AbortController()
    let active = true, url: string | undefined
    setFailed(undefined); setPreview(undefined)
    if (item.lifecycle === 'ready') {
      void api.content(item.id, item.sha256, controller.signal).then(blob => {
        if (!active || controller.signal.aborted || activeIdentity.current !== identity || activeApi.current !== api) return
        url = URL.createObjectURL(blob); setPreview({ url, identity })
      }, () => { if (active && !controller.signal.aborted && activeIdentity.current === identity && activeApi.current === api) setFailed(identity) })
    }
    return () => { active = false; controller.abort(); if (url) URL.revokeObjectURL(url) }
  }, [api, identity, item.lifecycle, retry])
  if (item.lifecycle !== 'ready') return <div className={css.previewUnavailable}>{c[item.lifecycle]}</div>
  if (failed === identity) return <div className={css.previewUnavailable}><span role="alert">{c.previewError}</span>
    <button type="button" className={shared.ghost} onClick={() => { setRetry(value => value + 1) }}>{c.previewRetry}</button></div>
  return <div className={css.preview} aria-busy={preview?.identity !== identity}>
    {preview?.identity === identity ? <img src={preview.url} alt={`${c.preview}: ${item.theme}`} width={item.width} height={item.height}
      onError={() => { setFailed(identity) }} /> : <div className={css.skeleton} aria-hidden="true" />}
  </div>
}

export function VisualMaterialLibrary({ api, language = 'zh', onNotify }: VisualMaterialLibraryProps): ReactNode {
  const c: Copy = copy[language]
  const [scope, setScope] = useState<'owned' | 'available'>('owned')
  const [draft, setDraft] = useState<Filters>(emptyFilters)
  const [filters, setFilters] = useState<Filters>(emptyFilters)
  const [page, setPage] = useState<VisualMaterialPage>()
  const [cursors, setCursors] = useState<(string | undefined)[]>([undefined])
  const [quota, setQuota] = useState<VisualMaterialQuota>()
  const [quotaError, setQuotaError] = useState(false)
  const [error, setError] = useState('')
  const [busy, setBusy] = useState<string>()
  const [refresh, setRefresh] = useState(0)
  const [editing, setEditing] = useState<{ id: string; revision: number; tags: string }>()
  const [confirming, setConfirming] = useState<string>()
  const requestGeneration = useRef(0)
  const pending = useRef<AbortController | null>(null)
  const notify = useRef(onNotify); notify.current = onNotify
  const lastApi = useRef(api)
  const activeApi = useRef(api); activeApi.current = api
  const cursor = cursors[cursors.length - 1]
  useEffect(() => {
    const controller = new AbortController(), generation = ++requestGeneration.current
    pending.current?.abort(); pending.current = controller
    if (lastApi.current !== api) { lastApi.current = api; setPage(undefined); setQuota(undefined); setQuotaError(false); setEditing(undefined); setConfirming(undefined) }
    setBusy('load'); setError('')
    const input = searchInput(filters)
    const load = scope === 'owned' ? api.owned({ lifecycle: filters.lifecycle, cursor, limit: 12 }, controller.signal)
      : api.search({ ...input, cursor }, controller.signal)
    void load.then(next => {
      if (controller.signal.aborted || generation !== requestGeneration.current || activeApi.current !== api) return
      setPage(next)
    }, cause => {
      if (controller.signal.aborted || generation !== requestGeneration.current || activeApi.current !== api) return
      setError(errorText(cause, c))
      if (cause instanceof VisualMaterialApiError && (cause.status === 401 || cause.status === 403)) { setPage(undefined); setQuota(undefined); setEditing(undefined); setConfirming(undefined); controller.abort() }
    }).finally(() => { if (generation === requestGeneration.current) { setBusy(undefined); pending.current = null } })
    void api.quota(controller.signal).then(next => {
      if (!controller.signal.aborted && generation === requestGeneration.current && activeApi.current === api) { setQuota(next); setQuotaError(false) }
    }, () => { if (!controller.signal.aborted && generation === requestGeneration.current && activeApi.current === api) setQuotaError(true) })
    return () => { controller.abort(); requestGeneration.current++; pending.current?.abort(); pending.current = null }
  }, [api, scope, filters, cursor, refresh])
  const cancel = (): void => {
    requestGeneration.current++; pending.current?.abort(); pending.current = null; setBusy(undefined); setEditing(undefined); setConfirming(undefined)
    if (busy && busy !== 'load') notify.current?.({ tone: 'error', message: c.canceledAction })
  }
  const reload = (): void => { cancel(); setRefresh(value => value + 1) }
  const submit = (event: FormEvent): void => {
    event.preventDefault()
    try { searchInput(draft); cancel(); setFilters({ ...draft }); setCursors([undefined]); setPage(undefined); setError('') }
    catch { setError(c.invalid) }
  }
  const manage = (item: VisualMaterialDescriptor, action: Omit<ManageVisualMaterial, 'operationId' | 'expectedRevision'>): void => {
    if (pending.current) return
    const controller = new AbortController(), generation = ++requestGeneration.current
    pending.current = controller; setBusy(item.id); setError('')
    const input: ManageVisualMaterial = { ...action, expectedRevision: item.revision, operationId: crypto.randomUUID() }
    void api.manage(item.id, input, controller.signal).then(result => {
      if (controller.signal.aborted || generation !== requestGeneration.current || activeApi.current !== api) return
      setPage(current => current ? { ...current, items: current.items.map(entry => entry.id === item.id ? result.material : entry) } : current)
      setEditing(undefined); setConfirming(undefined); notify.current?.({ tone: 'success', message: c.saved })
      setRefresh(value => value + 1)
    }, cause => {
      if (controller.signal.aborted || generation !== requestGeneration.current || activeApi.current !== api) return
      const message = errorText(cause, c); setError(message); notify.current?.({ tone: 'error', message })
      if (cause instanceof VisualMaterialApiError && (cause.status === 401 || cause.status === 403)) { setPage(undefined); setQuota(undefined); setEditing(undefined); setConfirming(undefined) }
    }).finally(() => { if (generation === requestGeneration.current) { setBusy(undefined); pending.current = null } })
  }
  const saveTags = (item: VisualMaterialDescriptor): void => {
    if (!editing || editing.revision !== item.revision) { setError(c.conflict); return }
    const tags = tagsOf(editing.tags)
    if (tags.length > 12 || tags.some(tag => tag.length > 48)) { setError(c.invalid); return }
    manage(item, { updateTags: tags })
  }
  const currentPage = lastApi.current === api ? page : undefined
  const currentQuota = lastApi.current === api ? quota : undefined
  const visible = scope === 'owned' ? currentPage?.items.filter(item => matches(item, filters)) : currentPage?.items
  return <div className={css.root} data-visual-material-library="" aria-busy={busy !== undefined}>
    <AdminToolbar><div><AdminCardTitle>{c.title}</AdminCardTitle><AdminCardMeta>{c.hint}</AdminCardMeta></div>
      <AdminCardActions><button type="button" className={shared.ghost} disabled={busy !== undefined} onClick={reload}>{c.refresh}</button>
        {busy && <button type="button" className={shared.ghost} onClick={cancel}>{c.cancel}</button>}</AdminCardActions></AdminToolbar>
    {currentQuota && <p className={css.usage}>{c.storage}: {currentQuota.account.count} · {c.bytes}: {(currentQuota.account.bytes / 1024 / 1024).toLocaleString(language === 'zh' ? 'zh-CN' : 'en-US', { maximumFractionDigits: 1 })} MiB</p>}
    {quotaError && <p className={css.hint}>{c.usageError}</p>}
    <AdminSectionTabs label={c.title} items={[{ id: 'owned', label: c.owned }, { id: 'available', label: c.available }]} value={scope}
      onChange={next => { cancel(); setScope(next); setPage(undefined); setCursors([undefined]) }}>
      <form className={css.filters} onSubmit={submit} aria-label={c.search}>
        <label className={shared.field}><span className={shared.fieldLabel}>{c.query}</span><input className={shared.input} maxLength={200} value={draft.query} onChange={event => { setDraft({ ...draft, query: event.target.value }) }} /></label>
        <label className={shared.field}><span className={shared.fieldLabel}>{c.theme}</span><input className={shared.input} maxLength={120} value={draft.theme} onChange={event => { setDraft({ ...draft, theme: event.target.value }) }} /></label>
        <label className={shared.field}><span className={shared.fieldLabel}>{c.purpose}</span><input className={shared.input} maxLength={120} value={draft.purpose} onChange={event => { setDraft({ ...draft, purpose: event.target.value }) }} /></label>
        <label className={shared.field}><span className={shared.fieldLabel}>{c.kind}</span><select className={shared.select} value={draft.kind} onChange={event => { setDraft({ ...draft, kind: event.target.value as Filters['kind'] }) }}>
          <option value="">{c.all}</option><option value="environment">{c.environment}</option><option value="material">{c.material}</option></select></label>
        <label className={shared.field}><span className={shared.fieldLabel}>{c.tags}</span><input className={shared.input} maxLength={600} value={draft.tags} onChange={event => { setDraft({ ...draft, tags: event.target.value }) }} /></label>
        <label className={shared.field}><span className={shared.fieldLabel}>{c.style}</span><input className={shared.input} maxLength={120} value={draft.style} onChange={event => { setDraft({ ...draft, style: event.target.value }) }} /></label>
        <label className={shared.field}><span className={shared.fieldLabel}>{c.width}</span><input className={shared.input} type="number" min={1} max={4096} value={draft.width} onChange={event => { setDraft({ ...draft, width: event.target.value }) }} /></label>
        <label className={shared.field}><span className={shared.fieldLabel}>{c.height}</span><input className={shared.input} type="number" min={1} max={4096} value={draft.height} onChange={event => { setDraft({ ...draft, height: event.target.value }) }} /></label>
        {scope === 'owned' && <label className={shared.field}><span className={shared.fieldLabel}>{c.lifecycle}</span><select className={shared.select} value={draft.lifecycle}
          onChange={event => { setDraft({ ...draft, lifecycle: event.target.value as Filters['lifecycle'] }) }}>{(['all', 'ready', 'deleted', 'pending', 'failed', 'canceled'] as const).map(value => <option key={value} value={value}>{c[value]}</option>)}</select></label>}
        <button type="submit" className={shared.primary}>{c.search}</button>
      </form>
      {scope === 'owned' && <p className={css.hint}>{c.ownedHint}</p>}
      {error && <p className={shared.error} role="alert">{error}</p>}
      {!currentPage ? error ? <AdminEmpty><button type="button" className={shared.ghost} onClick={reload}>{c.refresh}</button></AdminEmpty>
        : <div className={css.grid} aria-label={c.title}>{Array.from({ length: 3 }, (_, index) => <div key={index} className={css.loadingTile} aria-hidden="true" />)}</div>
        : <><div className={css.grid}>{visible?.map(item => <AdminCard key={item.id} className={css.tile} testId={`visual-material-${item.id}`}>
          <MaterialPreview item={item} api={api} c={c} />
          <AdminCardHead><AdminCardTitle>{item.theme}</AdminCardTitle><span className={css.badge}>{c[item.visibility]} · {c[item.lifecycle]}</span></AdminCardHead>
          <dl className={css.details}><dt>{c.purpose}</dt><dd>{item.purpose}</dd><dt>{c.kind}</dt><dd>{c[item.kind]}</dd>
            <dt>{c.size}</dt><dd>{item.width} × {item.height}</dd><dt>{c.style}</dt><dd>{item.style || '—'}</dd>
            <dt>{c.model}</dt><dd>{item.model}</dd></dl>
          <div className={css.tags}>{item.tags.map(tag => <span key={tag}>{tag}</span>)}</div>
          {scope === 'owned' && <><AdminCardActions>
            {item.lifecycle === 'ready' && <><button type="button" className={shared.ghost} disabled={busy !== undefined} onClick={() => { setEditing({ id: item.id, revision: item.revision, tags: item.tags.join(', ') }); setConfirming(undefined) }}>{c.editTags}</button>
              <button type="button" className={shared.ghost} disabled={busy !== undefined} onClick={() => { manage(item, { visibility: item.visibility === 'private' ? 'school' : 'private' }) }}>{item.visibility === 'private' ? c.share : c.unshare}</button>
              <button type="button" className={shared.danger} disabled={busy !== undefined} onClick={() => { setEditing(undefined); setConfirming(item.id) }}>{c.remove}</button></>}
            {item.lifecycle === 'deleted' && <button type="button" className={shared.ghost} disabled={busy !== undefined} onClick={() => { manage(item, { restore: true }) }}>{c.restore}</button>}
          </AdminCardActions>
          {confirming === item.id && <div className={css.confirm} role="group" aria-label={c.confirm}><p>{c.deleteHint}</p><AdminCardActions>
            <button type="button" className={shared.ghost} onClick={cancel}>{c.cancel}</button><button type="button" className={shared.danger} disabled={busy !== undefined} onClick={() => { manage(item, { softdelete: true }) }}>{c.confirm}</button></AdminCardActions></div>}
          {editing?.id === item.id && <form className={css.tagEditor} onSubmit={event => { event.preventDefault(); saveTags(item) }} aria-label={c.editTags}>
            <label className={shared.field}><span className={shared.fieldLabel}>{c.tags}</span><input className={shared.input} maxLength={600} value={editing.tags} disabled={busy !== undefined}
              onChange={event => { setEditing({ ...editing, tags: event.target.value }) }} /></label><p className={css.hint}>{c.tagHint}</p>
            <AdminCardActions><button type="button" className={shared.ghost} onClick={cancel}>{c.cancel}</button><button type="submit" className={shared.primary} disabled={busy !== undefined}>{c.save}</button></AdminCardActions></form>}
          </>}
        </AdminCard>)}</div>
          {visible?.length === 0 && <AdminEmpty>{c.empty}</AdminEmpty>}
          <AdminToolbar className={css.pagination}><span>{c.page} {cursors.length}</span><AdminCardActions>
            <button type="button" className={shared.ghost} disabled={busy !== undefined || cursors.length <= 1} onClick={() => { cancel(); setPage(undefined); setCursors(current => current.slice(0, -1)) }}>{c.back}</button>
            <button type="button" className={shared.ghost} disabled={busy !== undefined || !currentPage.nextCursor} onClick={() => { if (!currentPage.nextCursor) return; cancel(); setPage(undefined); setCursors(current => [...current, currentPage.nextCursor]) }}>{c.more}</button>
          </AdminCardActions></AdminToolbar>
        </>}
    </AdminSectionTabs>
  </div>
}
