import { describe, expect, it } from 'vitest'
import { createMechanicsScene, createWaveInterferenceScene } from '@physicsos/physics-scene'
import { createMechanicsWorkspaceRuntime } from '../src/client/physics/mechanics-workspace-runtime.ts'
import { createWaveWorkspaceRuntime } from '../src/client/physics/wave-workspace-runtime.ts'

describe('integrated experiment playback contracts', () => {
  it('stops an explicitly bounded orbit arc and scales teaching time from the actual full period', () => {
    const runtime = createMechanicsWorkspaceRuntime(createMechanicsScene({ model: 'circular_orbit', gravitationalParameter: 32, orbitRadius: 2, endTime: 1 }))
    const start = runtime.getSnapshot()
    expect(start.clock.total).toBe(1)
    runtime.setRunning(true)
    expect(runtime.advance(1).clock.time).toBeCloseTo(Math.PI / 20, 12)
    const finish = runtime.advance(20)
    expect(finish.clock).toMatchObject({ time: 1, total: 1, running: false })
    expect(runtime.advance(20).view.bodies).toEqual(finish.view.bodies)
    const replay = runtime.setRunning(true)
    expect(replay.clock.time).toBe(0)
    const full = createMechanicsWorkspaceRuntime(createMechanicsScene({ model: 'circular_orbit', gravitationalParameter: 32, orbitRadius: 2 }))
    full.setRunning(true)
    const looped = full.advance(25)
    expect(looped.clock.time).toBeCloseTo(Math.PI / 4, 12)
    expect(looped.clock.running).toBe(true)
  })

  it('preserves causal interference propagation across phase wraps and pause/resume', () => {
    const runtime = createWaveWorkspaceRuntime(createWaveInterferenceScene())
    runtime.editParameter('wave-speed', 0.5)
    const reach = () => Math.max(0, ...(runtime.getSnapshot().view.waveFronts ?? []).map(front => front.radius))
    runtime.setRunning(true)
    runtime.advance(3.1)
    expect(reach()).toBeGreaterThanOrEqual(140)
    expect(runtime.getSnapshot().clock.time).toBeCloseTo(0.1, 10)
    runtime.advance(1)
    expect(reach()).toBeGreaterThanOrEqual(140)
    runtime.setRunning(false)
    const paused = runtime.getSnapshot().view
    expect(runtime.advance(10).view).toEqual(paused)
    runtime.setRunning(true)
    runtime.advance(0.1)
    expect(reach()).toBeGreaterThanOrEqual(140)
    runtime.setObservable('waveSpeed', false)
    expect(reach()).toBeGreaterThanOrEqual(140)
    expect(runtime.getSnapshot().view.overlay.readout.some(text => text.includes('累计传播时间') && text.includes('本周期'))).toBe(true)
    const stepped = runtime.step(0.05)
    expect(stepped.clock.time).toBeCloseTo(0.25, 10)
    expect(stepped.clock.running).toBe(false)
    expect(reach()).toBeGreaterThanOrEqual(140)
    const back = runtime.step(-0.1)
    expect(back.clock.time).toBeCloseTo(0.15, 10)
    expect(back.clock.running).toBe(false)
    expect(reach()).toBeGreaterThanOrEqual(140)
    for (const invalid of [Number.NaN, Number.POSITIVE_INFINITY, Number.NEGATIVE_INFINITY]) {
      expect(runtime.step(invalid).view).toEqual(back.view)
    }
    runtime.setRunning(true)
    runtime.advance(0.1)
    expect(reach()).toBeGreaterThanOrEqual(140)
    expect(runtime.step(-10).clock.time).toBe(0)
    expect(reach()).toBe(0)
    runtime.seek(0.2)
    expect(runtime.getSnapshot().clock.running).toBe(false)
    expect(reach()).toBeLessThanOrEqual(10)
    runtime.seek(0)
    expect(reach()).toBe(0)
    runtime.setRunning(true)
    runtime.advance(3)
    runtime.editParameter('frequency', 12)
    expect(runtime.getSnapshot().clock).toMatchObject({ time: 0, running: false })
    expect(reach()).toBe(0)
  })
})
