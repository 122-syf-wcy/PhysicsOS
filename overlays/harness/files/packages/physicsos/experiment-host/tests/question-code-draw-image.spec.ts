const disposals: (() => Promise<void>)[] = []
afterEach(async () => { for (const dispose of disposals.splice(0).reverse()) await dispose() })
async function create(rendererJs: string, withAsset = false) {
  const root = await mkdtemp(join(tmpdir(), 'question-image-geometry-'))
  const loaded = await host(root)
  const domain = await openQuestionCodeDomain(loaded.ctx)
  const pngChunk = (name: string, data: Buffer) => {
    const header = Buffer.alloc(4), tail = Buffer.alloc(4), tag = Buffer.from(name)
    header.writeUInt32BE(data.length)
    tail.writeUInt32BE(crc32(Buffer.concat([tag, data])))
    return Buffer.concat([header, tag, data, tail])
  }
  const head = Buffer.alloc(13); head.writeUInt32BE(256); head.writeUInt32BE(256, 4); head[8] = 8; head[9] = 6
  const png = Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]), pngChunk('IHDR', head), pngChunk('IDAT', deflateSync(Buffer.alloc(256 * 1025))), pngChunk('IEND', Buffer.alloc(0))])
  const images = new QuestionCodeAssets({ env: { PHYSICSOS_IMAGE_API_KEY: 'fixture-key' }, fetchImpl: async () => Response.json({ data: [{ b64_json: png.toString('base64') }] }) })
  const service = new QuestionCodeArtifactService(domain, { imageAssets: images, root: join(root, 'private'), identity: () => ({ actorOf: () => contributor, record: async () => {}, sessionOwnerKey: () => contributor.userKey }) })
  disposals.push(async () => {
    await service.close()
    await domain.close()
    await loaded.close()
    await rm(root, { recursive: true, force: true })
  })
  await service.initialize()
  const originalScene = createConvexLensScene()
  const scope = { ownerSessionId: 'parent', generationId: 'job', scene: originalScene }
  const asset = withAsset ? await service.generateAsset({ ...scope, prompt: 'Natural wood lab without text', kind: 'environment', signal: new AbortController().signal }) : undefined
  const exactSource = asset ? rendererJs.replace('./assets/parts3d/mechanics/ball.png', asset.path) : rendererJs
  const ref = await service.create({ ...(withAsset ? { generationId: 'job' } : {}), ownerSessionId: 'parent', childSessionId: 'child', experimentId: 'convex-lens', scene: originalScene, source: { title: '图像材质装置', summary: '', rendererJs: exactSource, stylesheet: '' } })
  if (asset) {
    expect((await service.source(contributor, ref.artifactId, ref.sha256)).source.rendererJs).toBe(exactSource)
    const row = domain.table('artifacts').get(ref.artifactId)
    expect(row?.files).toEqual(expect.arrayContaining([expect.objectContaining({ name: 'dist/' + asset.path.slice(2), sha256: asset.sha256 })]))
    const preview = service.preview(contributor, ref.artifactId, ref.sha256)
    const raw = new URL(preview.entryUrl.replace('/embed/question/', '/question/'), 'http://local')
    expect((await service.asset(new URL(asset.path, raw)))?.bytes).toEqual(png)
    expect(service.assetManifest(scope)).toEqual([asset])
  }
  return ref
}
const fixture = (paint: string) => `const image = new Image(); image.src = './assets/parts3d/mechanics/ball.png';
export async function renderFrame(snapshot) {
  await image.decode();
  const canvas = document.createElement('canvas'); document.getElementById('canvas').replaceChildren(canvas);
  const ctx = canvas.getContext('2d'); const point = snapshot.view.opticalObjects[0].at;
  ${paint}
}`
it.each([
  'ctx.drawImage(image, point.x, point.y);',
  'ctx.drawImage(image, point.x, point.y, 24, 24);',
  'ctx.drawImage(image, 0, 0, 100, 100, point.x, point.y, 24, 24);',
  'ctx.translate(point.x, point.y); ctx.drawImage(image, -12, -12, 24, 24);',
])('accepts engine-driven destination geometry in native image drawing: %s', async (paint) => {
  await expect(create(fixture(paint))).resolves.toMatchObject({ rendererKind: 'independent' })
})
it.each([
  'ctx.drawImage(image, 0, 0, 800, 500);',
  'ctx.drawImage(image, point.x, point.y, 100, 100, 0, 0, 24, 24);',
  'ctx.translate(point.x, point.y); ctx.resetTransform(); ctx.drawImage(image, 0, 0);',
])('rejects image-only backgrounds or engine-driven crop with constant destination: %s', async (paint) => {
  await expect(create(fixture(paint))).rejects.toMatchObject({ code: 'INVALID_SOURCE' })
})

it('freezes real generated bytes with their hash and unchanged authored source in the owned package', async () => {
  await expect(create(fixture('ctx.drawImage(image, point.x, point.y, 24, 24);'), true)).resolves.toMatchObject({ rendererKind: 'independent' })
})
