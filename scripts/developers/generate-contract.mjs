/** Generate shared V2 validators; --check refuses stale consumers. Node >=24.7. */
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { stripTypeScriptTypes } from 'node:module'
import {
  manifestV2Example,
  parametersV2Document,
  casesV2Document,
} from '../../overlays/harness/files/packages/physicsos/experiment-host/src/contract-v2.ts'
const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..')
const canonical = 'overlays/harness/files/packages/physicsos/experiment-host/src'
const banner = '// Generated by scripts/developers/generate-contract.mjs. Do not edit.\n'
const generated = new Map()
const wire = banner + (await readFile(resolve(root, canonical, 'contract-wire.ts'), 'utf8'))
for (const target of [
  'developer-kit/experiment-template/src/contract-wire.ts',
  'developer-kit/experiment-template/tools/contract-wire.ts',
  'overlays/harness/files/packages/client/ui-physicsos/src/client/experiments/contract-wire.ts',
])
  generated.set(target, wire)
generated.set(
  'developer-kit/experiment-template/tools/contract-v2.ts',
  banner + (await readFile(resolve(root, canonical, 'contract-v2.ts'), 'utf8')),
)
for (const name of ['package-resources.ts', 'html.ts', 'package-limits.ts']) {
  generated.set(
    `developer-kit/experiment-template/tools/${name}`,
    banner + (await readFile(resolve(root, canonical, name), 'utf8')),
  )
}
const optics = (
  await readFile(resolve(root, 'packages/engine-optics/src/imaging.ts'), 'utf8')
).replace(/^import type[\s\S]*?from ['"][^'"]+['"]\r?\n/m, '')
generated.set(
  'developer-kit/experiment-template/tools/platform-optics.mjs',
  banner +
    stripTypeScriptTypes(optics)
      .split('\n')
      .map((line) => line.trimEnd())
      .join('\n'),
)
generated.set(
  'overlays/harness/files/apps/web/public/physicsos/developers/contract-profile.js',
  banner +
    'export const CONTRACT_PROFILE = ' +
    JSON.stringify(
      {
        experimentId: manifestV2Example.experimentId,
        manifest: manifestV2Example,
        parameters: parametersV2Document,
        cases: casesV2Document,
      },
      null,
      2,
    ) +
    '\n',
)
let stale = false
for (const [target, contents] of generated) {
  const path = resolve(root, target)
  if (process.argv.includes('--check')) {
    let actual
    try {
      actual = await readFile(path, 'utf8')
    } catch {
      actual = undefined
    }
    if (actual !== contents) {
      process.stderr.write(`Stale generated contract: ${target}\n`)
      stale = true
    }
  } else {
    await mkdir(dirname(path), { recursive: true })
    await writeFile(path, contents)
  }
}
if (stale) process.exitCode = 1
else
  process.stdout.write(
    `${process.argv.includes('--check') ? 'Verified' : 'Generated'} ${generated.size} contract files.\n`,
  )
