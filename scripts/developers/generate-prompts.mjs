/** Generate prompt defaults/portable format only; immutable template archives are not touched. */
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { stripTypeScriptTypes } from 'node:module'
import { agentInstructions } from '../../overlays/harness/files/apps/web/public/physicsos/developers/standards.js'

const root = new URL('../../', import.meta.url)
const check = process.argv.includes('--check')
const host = 'overlays/harness/files/packages/physicsos/experiment-host/src/'
const docs = 'overlays/harness/files/apps/web/public/physicsos/developers/'
const fixed = new Set(['固定 V2 契约（必须）', '实验包边界（必须）', '物理与状态（必须）', '提交与验证（必须）'])
const sections = agentInstructions('convex-lens', { baseOnly: true }).split(/(?=^## )/m).slice(1)
const operational = [], contract = []
for (const section of sections) {
  const heading = /^## ([^\n]+)/.exec(section)?.[1]
  ;(fixed.has(heading) ? contract : operational).push(section.trim())
}
if (contract.length !== fixed.size || !operational.length) throw new Error('Canonical prompt sections changed; update the explicit ownership map')
const release = JSON.parse(await readFile(new URL(docs + 'downloads/template-release.json', root), 'utf8'))
const seed = { body: operational.join('\n\n'), binding: { release, contractMarkdown: contract.join('\n\n') } }
const format = await readFile(new URL(host + 'prompt-format.ts', root), 'utf8')
const banner = '// Generated by scripts/developers/generate-prompts.mjs; do not edit.\n'
const outputs = [
  [host + 'prompt-seed.ts', banner + `import type { PromptSeed } from './prompt-format.ts'\nexport const PROMPT_SEED: PromptSeed = ${JSON.stringify(seed, null, 2)}\n`],
  [docs + 'prompt-format.js', banner + stripTypeScriptTypes(format)],
  ['overlays/harness/files/packages/client/ui-physicsos/src/client/developer-prompt-format.ts', banner + format],
]
for (const [path, content] of outputs) {
  const url = new URL(path, root)
  if (check) {
    if (await readFile(url, 'utf8').catch(() => '') !== content) throw new Error(`Generated prompt artifact differs: ${path}`)
  } else { await mkdir(dirname(fileURLToPath(url)), { recursive: true }); await writeFile(url, content) }
}
console.log(`${check ? 'Verified' : 'Generated'} ${outputs.length} prompt artifacts; frozen template ${release.sha256}`)
