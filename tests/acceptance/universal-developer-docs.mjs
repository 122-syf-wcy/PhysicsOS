import { chromium, expect } from '@playwright/test'
import { readFile, mkdir } from 'node:fs/promises'
const base = process.env.PHYSICSOS_CONTRIBUTION_BASE ?? 'http://127.0.0.1:3095'
const output = '/tmp/physicsos-universal-docs-check'
await mkdir(output, { recursive: true })
const browser = await chromium.launch({headless:true,args:['--no-sandbox','--disable-dev-shm-usage','--disable-gpu']})
try {
  const context = await browser.newContext({viewport:{width:1440,height:1000}})
  await context.grantPermissions(['clipboard-read','clipboard-write'],{origin:base})
  const page = await context.newPage()
  const errors=[];page.on('pageerror',error=>errors.push(error.message))
  await page.goto(`${base}/physicsos/developers/index.html?experiment=pinhole#/agents`)
  const selector = page.getByLabel('已注册实验契约',{exact:true})
  await expect(selector.locator('option')).toHaveCount(76)
  await expect(page.locator('.agent-preview')).toContainText('pinhole')
  await expect(page.locator('.sidebar-kit')).toHaveAttribute('href','/physicsos/experiments/pinhole/template')
  await page.getByLabel('本次任务说明（可选）').fill('保持平台结果，优化玻璃按钮和交互。')
  const text=await page.locator('.agent-preview').textContent()
  await page.getByRole('button',{name:'复制 AGENTS.md',exact:true}).click()
  expect(await page.evaluate(()=>navigator.clipboard.readText())).toBe(text)
  const [download]=await Promise.all([page.waitForEvent('download'),page.getByRole('button',{name:'下载 AGENTS.md',exact:true}).click()])
  await download.saveAs(output+'/agents.md')
  expect(await readFile(output+'/agents.md','utf8')).toBe(text)
  const [top]=await Promise.all([page.waitForEvent('download'),page.locator('[data-universal-download]').click()])
  await top.saveAs(output+'/header-agents.md')
  expect(await readFile(output+'/header-agents.md','utf8')).toBe(text)
  await page.route('**/physicsos/experiments/pinhole/developer-prompt',route=>route.fulfill({status:503,body:'unavailable'}))
  await page.getByRole('button',{name:'重新加载提示词',exact:true}).click()
  await expect(page.getByRole('alert')).toContainText('加载失败')
  await expect(page.locator('[data-universal-download]')).toBeDisabled()
  await expect(page.getByRole('button',{name:'复制 AGENTS.md',exact:true})).toBeDisabled()
  await page.unroute('**/physicsos/experiments/pinhole/developer-prompt')
  await page.getByRole('button',{name:'重新加载提示词',exact:true}).click()
  await expect(page.getByRole('button',{name:'复制 AGENTS.md',exact:true})).toBeEnabled()
  await selector.selectOption('series-circuit')
  await expect(page.locator('.agent-preview')).toContainText('series-circuit')
  await expect(page.locator('.agent-preview')).toContainText('优化玻璃按钮')
  await expect(page.locator('.sidebar-kit')).toHaveAttribute('href','/physicsos/experiments/series-circuit/template')
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  expect(errors).toEqual([])
  console.log('PASS all76 developer prompt choices, bound copy/header/download equality, retry fail-closed, task preservation, selected template and mobile')
}catch(error){console.error(String(error.stack??error));process.exitCode=1}
finally{await browser.close()}
